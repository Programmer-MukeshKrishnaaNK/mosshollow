/**
 * THE MEADOW
 *
 * East of the homestead, through the gate. Designed to feel like the opposite
 * of the farm: open where the homestead is enclosed, and empty where it is
 * cluttered.
 *
 *  - A stream runs the whole height of the map and wanders while it does it.
 *    You cross at one place, on stones somebody laid, which makes the crossing
 *    a decision rather than a fact.
 *  - The far side is where the valley stops being tended. Boulders in the
 *    north-east, a grove gone wild in the south-west.
 *  - And a floor. Ten metres by eight, cut stone, with grass coming through
 *    it, and no walls at all. Whatever stood here was taken apart carefully.
 *  - The third bell marker stands in the middle of that floor. It is the only
 *    one of the three that is still where somebody put it on purpose.
 */

